#!/usr/bin/env python3
"""Convert HuCard wavetable spectra to native YM2612 patches.
Most use four additive carriers; dense waves 6/21/24 use a modulated carrier and
two additive carriers. Wave 2 uses three carriers sharing a feedback modulator.
Phase and discarded harmonics need listening QA.
"""
import cmath
import json
import math
from pathlib import Path
from inspect_hucard_music import ROOT, metadata

# Algorithm 6 supplies a modulated carrier plus two additive carriers for
# these spectrally dense waves. Register order is 1,3,2,4; operator 1 is the
# modulator. Levels were fitted against actual YM output, including AC power.
FM_OVERRIDES = {
    2: ([3, 5, 3, 4], [39, 32, 18, 24]),
    6: ([1, 7, 3, 1], [8, 27, 17, 13]),
    21: ([1, 2, 3, 1], [8, 36, 22, 19]),
    24: ([1, 2, 10, 1], [16, 42, 22, 24]),
}

# Instrument 2 uses algorithm 5 with feedback 7: one modulator feeds three
# carriers. The packed byte is the YM B0 value, including feedback bits 3..5.
FM_CONTROLS = {2: 5 | (7 << 3)}


def patches(rom):
    result=[]; report=[]
    for ins in metadata(rom)['instruments']:
        wave=ins['wave']; mean=sum(wave)/32
        spectrum=[abs(sum((v-mean)*cmath.exp(-2j*math.pi*k*n/32) for n,v in enumerate(wave)))/16 for k in range(17)]
        harmonics=sorted(range(1,16),key=lambda k:-spectrum[k])[:4]
        # Match AC power before the common 12 dB mix headroom. Four carriers
        # otherwise make spectrally complex instruments substantially quieter.
        source_rms=math.sqrt(sum((v-mean)**2 for v in wave)/32)
        selected_rms=math.sqrt(sum(spectrum[k]**2 for k in harmonics)/2)
        gain=source_rms/selected_rms if selected_rms else 1
        # TL=16 is headroom, not a lower clamp: a square wave's fundamental
        # can exceed amplitude 16 while its samples stay within five bits.
        levels=[min(127,max(0,round(-20*math.log10(max(spectrum[k]*gain/16,1e-8))/.75)+16)) for k in harmonics]
        if ins['id'] in FM_OVERRIDES:
            harmonics, levels = FM_OVERRIDES[ins['id']]
        result.append(harmonics+levels)
        rendered_rms=math.sqrt(sum((16*10**((16-level)*.75/20))**2 for level in levels)/2)
        report.append(dict(instrument=ins['id'],operator_multipliers=harmonics,total_levels=levels,
                           algorithm=FM_CONTROLS.get(ins['id'], 6 if ins['id'] in FM_OVERRIDES else 7),
                           linear_baseline_retained_spectral_energy=selected_rms**2/source_rms**2 if source_rms else 1,
                           source_rms=source_rms,linear_baseline_selected_rms=selected_rms,linear_baseline_normalization_gain=gain,
                           normalized_rms=None if ins['id'] in FM_OVERRIDES else rendered_rms,
                           level_error_db=None if ins['id'] in FM_OVERRIDES else 20*math.log10(rendered_rms/source_rms) if source_rms else 0))
    return result,report


def emit(rom, output):
    rows,report=patches(rom)
    pitches=[]
    for numerator in (4404020,4444560):
        bank=[]
        for period in range(4096):
            divisor=period or 4096
            block=0
            fnum=(numerator+divisor//2)//divisor
            while fnum>2047 and block<7:
                block+=1;divisor*=2
                fnum=(numerator+divisor//2)//divisor
            bank.append((block<<11)|min(fnum,2047))
        pitches.append(bank)
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('/* Generated by tools/build_hucard_fm.py. */\n#include "hucard_fm.h"\n'
                      'const unsigned char hucard_fm_patches[32][8] = {\n'+
                      ',\n'.join('    {'+', '.join(map(str,row))+'}' for row in rows)+'\n};\n'+
                      'const unsigned char hucard_fm_algorithms[32] = {'+
                      ', '.join(str(r['algorithm']) for r in report)+'};\n'+
                      '#ifndef __m68k__\nconst unsigned short hucard_fm_pitch[2][4096] = {\n'+
                      ',\n'.join('{'+','.join(map(str,bank))+'}' for bank in pitches)+'\n};\n#endif\n')
    # Assembly read-only data is linked before the aligned Z80 sound bank,
    # using the headroom recovered by packing CPU-only zone metadata.
    output.with_name('hucard_pitch.s').write_text(
        '/* Generated by tools/build_hucard_fm.py. */\n.section .rodata\n.balign 2\n'
        '.global hucard_fm_pitch\nhucard_fm_pitch:\n'+
        ''.join('.word '+','.join(str(v)for v in bank[i:i+16])+'\n'
                for bank in pitches for i in range(0,4096,16)))
    (ROOT/'.local/pce-hucard').mkdir(parents=True,exist_ok=True)
    (ROOT/'.local/pce-hucard/fm-patches.json').write_text(json.dumps(report,indent=2)+'\n')
    return report

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rom',type=Path,default=ROOT/'.local/pce-hucard/SideArms - Hyper Dyne (USA).pce')
    a=p.parse_args()
    emit(a.rom.read_bytes(),ROOT/'src/gen/hucard_fm_data.c')
