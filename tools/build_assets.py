far_out, home_rows = [], {}      # Home zone variants and far layers, see tools/parallax_split.py
home_zones = parallax_split.home_zones()
for zi, z in enumerate(zonecfg.ZONES):
    x0, y0, w, h = z['rect']
    cells = [(code[r, c], color[r, c]) for r in range(y0, y0 + h) for c in range(x0, x0 + w)]
    metas = sorted(set(cells))
    mid = {m: i for i, m in enumerate(metas)}
    # blocks = each 8x8 subtile of each metatile
    blocks = []
    for (cd, cl) in metas:
        t = bgt[cd]
        for sy in range(4):
            for sx in range(4):
                sub = t[sy * 8:sy * 8 + 8, sx * 8:sx * 8 + 8]
                hist = {}
                for pen, n in zip(*np.unique(sub, return_counts=True)):
                    if pen != 15:
                        c = MD[cl * 16 + int(pen)]; hist[c] = hist.get(c, 0) + int(n)
                blocks.append(hist)
    pals, assign = fit(blocks, 2, 15, fixed=[seed0, seed1])
    tiles = bytearray(); attrs = bytearray(); bi = 0
    for (cd, cl) in metas:
        t = bgt[cd]
        for sy in range(4):
            for sx in range(4):
                sub = t[sy * 8:sy * 8 + 8, sx * 8:sx * 8 + 8]
                p = int(assign[bi]); bi += 1
                lut = {pen: (0 if pen == 15 else 1 + nearest(MD[cl * 16 + pen], pals[p])) for pen in range(16)}
                px = np.vectorize(lut.get)(sub)
                tiles += tile_bytes(px)
                # nametable template: palette + high priority + subtile index; 0 = empty
                idx = sy * 4 + sx
                attrs += struct.pack('>H', 0 if not px.any() else (0x8000 | (p << 13) | idx))
    if zi == 0:
        # R1's authored stone ramps assign their own meaning to pen 15.
        # Preserve the donor before Normal-only material repairs reuse it.
        (GEN / 'bc_r1_donor_tiles.bin').write_bytes(tiles)
        (GEN / 'bc_r1_donor_attr.bin').write_bytes(attrs)
        (GEN / 'bc_r1_donor_pal.bin').write_bytes(be16(
            [v for bank in pals for v in [0]+[md_word(c) for c in bank]+[0]*(15-len(bank))]))
    if zi in (6, 19, 20):
        from normal_background_shading import refit_materials
        assert zi not in home_zones and zi not in parallax_split.far_layers()
        refit_materials(zi, tiles, attrs, pals, metas, bgt, MD)
    if zi == 10:
        # Keep the original subtile bank assignments: Home variants use these
        # same assignments, and the far texture retains all displayed colors.
        from normal_background_shading import refit_materials
        recipe = json.loads((Path(__file__).parent/'data/normal_zone10_palette_fit.json').read_text())
        assert list(map(int, assign)) == recipe['assignments']
        refit_materials(zi, tiles, attrs, pals, metas, bgt, MD)
    if zi == 16:
        from normal_background_shading import restore_zone16_blue
        assert zi not in home_zones and zi not in parallax_split.far_layers()
        restore_zone16_blue(tiles, attrs, pals, metas, bgt, MD)
    if zi in (0, 3, 5, 12, 13, 14, 16, 17, 18):
        from normal_background_shading import restore_materials
        assert zi not in home_zones and zi not in parallax_split.far_layers()
        restore_materials(zi, tiles, attrs, pals, metas, bgt, MD)
    if zi == 3:
        from normal_background_shading import restore_local_shades
        restore_local_shades(zi, tiles, attrs, pals, metas, bgt, MD)
    if zi in (0, 5):
        from normal_background_shading import refit_materials
        assert zi not in home_zones and zi not in parallax_split.far_layers()
        refit_materials(zi, tiles, attrs, pals, metas, bgt, MD)
    zmap = [mid[(code[r, c], color[r, c])] | (((flags[r, c] & 1) << 14) | ((flags[r, c] & 2) << 14))
            for r in range(y0, y0 + h) for c in range(x0, x0 + w)]
    palwords = []
    for p in pals:
        palwords += [0] + [md_word(c) for c in p] + [0] * (15 - len(p))
    emit(f'zone{zi}_tiles', bytes(tiles), comment=f'{len(metas)} metatiles x16 ')
    emit(f'zone{zi}_attr', bytes(attrs), 'u16', comment='16 nametable templates per metatile (0 = empty) ')
    emit(f'zone{zi}_map', be16(zmap), 'u16', 'b0-11 meta, b14 hflip, b15 vflip ')
    emit(f'zone{zi}_pal', be16(palwords), 'u16', 'PAL0+PAL1 ')
    if zi in home_zones:
        # Home zone variant (tools/parallax_split.py, docs/parallax.md): changed cells use copies of
        # their metatiles - far-layer texture pixels cut out, wheel-boss sockets filled
        dark = lambda cl: min(range(15), key=lambda pen: sum(MD[cl * 16 + pen]))
        var, vmap = parallax_split.home_variant(zi, code, color, flags, mid, dark)
        vt = bytearray(); va = bytearray()
        for m, t in var:
            cd, cl = metas[m]
            for sy in range(4):
                for sx in range(4):
                    sub = t[sy * 8:sy * 8 + 8, sx * 8:sx * 8 + 8]
                    p = int(assign[m * 16 + sy * 4 + sx])
                    lut = {pen: (0 if pen == 15 else 1 + nearest(MD[cl * 16 + pen], pals[p])) for pen in range(16)}
                    px = np.vectorize(lut.get)(sub)
                    vt += tile_bytes(px)
                    va += struct.pack('>H', 0 if not px.any() else (0x8000 | (p << 13) | (sy * 4 + sx)))
        emit(f'zone{zi}h_tiles', bytes(vt), comment=f'Home variant: {len(var)} changed metatiles x16 ')
        emit(f'zone{zi}h_attr', bytes(va), 'u16', comment='their nametable templates ')
        emit(f'zone{zi}h_map', be16(vmap), 'u16', 'Home variant map (changed cells: metas >= zone metas) ')
        home_rows[zi] = len(var)
        print(f"zone {z['name']}: Home variant, {len(var)} changed metatiles")
    if zi in parallax_split.far_layers():
        ft, fw, tw, th = parallax_split.far_tiles(zi, pals, MD, nearest, tile_bytes)
        emit(f'zone{zi}_far_tiles', ft, comment=f'far texture, {len(ft) // 32} tiles ')
        emit(f'zone{zi}_far_map', be16(fw), 'u16', f'{tw}x{th} tiles of one period ')
        fl_ = parallax_split.far_layers()[zi]
        far_out.append(dict(zone=zi, name=fl_['name'], tiles=f'zone{zi}_far_tiles', ntiles=len(ft) // 32,
                            map=f'zone{zi}_far_map', w=tw, h=th, rect=[int(v) for v in fl_['rect']],
                            segs=[[int(v) for v in s] for s in fl_['segs']]))
        print(f"zone {z['name']}: far layer, {len(ft) // 32} tiles")
    zone_rows.append((z['name'], x0, y0, w, h, len(metas)))
    print(f"zone {z['name']}: {len(metas)} metatiles, palettes {[len(p) for p in pals]}")

