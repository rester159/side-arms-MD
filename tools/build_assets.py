header = ['/* Generated by tools/build_assets.py from the original ROM set. Do not edit. */',
          '#pragma once', '#include <genesis.h>', '']


def emit(name, data, ctype='u8', comment=''):
    (GEN / f'{name}.bin').write_bytes(data)
    symbols.append(name)
    header.append(f'extern const {ctype} {name}[];  /* {len(data)} bytes {comment}*/')


def be16(vals):
    return b''.join(struct.pack('>H', v & 0xffff) for v in vals)


def tile_bytes(px):
    """8x8 array of 4-bit indices -> 32 bytes Genesis tile."""
    out = bytearray()
    for row in px:
        for x in range(0, 8, 2):
            out.append(((int(row[x]) & 15) << 4) | (int(row[x + 1]) & 15))
    return bytes(out)


src = Source()
main = src.region('maincpu')
lo = main[0x14a37:0x14a37 + 0x400]; hi = main[0x14e37:0x14e37 + 0x400]
ARC = []  # arcade palette as 4-bit rgb tuples
for i in range(1024):
    r, g, b = palette_rgb(lo[i], hi[i])
    ARC.append((r // 17, g // 17, b // 17))
MD = [to_md(c) for c in ARC]

# ---------------------------------------------------------------- stars
# Arcade star colours 0x378..0x37F (colour 0 is black = no visible star).
# Bright colours are reserved: PAL0 idx1-3 (teal, blue, grey), PAL1 idx1-2 (olive, red);
# the dim shades fall back to the nearest reserved colour.
STAR = [MD[0x378 | k] for k in range(8)]
seed0 = [STAR[1], STAR[3], STAR[5]]
seed1 = [STAR[6], STAR[7]]
star_choice = {}
for k in range(1, 8):
    if STAR[k] == (0, 0, 0):
        continue
    opts = [(0, i, c) for i, c in enumerate(seed0)] + [(1, i, c) for i, c in enumerate(seed1)]
    best = min(opts, key=lambda o: sum((a - b) ** 2 for a, b in zip(o[2], STAR[k])))
    star_choice[k] = (best[0], 1 + best[1])
star = star_image(src.region('starfield'))
star_tiles = [bytes(32)]; star_index = {bytes(32): 0}; star_map = []
for cy in range(32):
    for cx in range(64):
        cell = star[cy * 8:cy * 8 + 8, cx * 8:cx * 8 + 8]
        px = np.zeros((8, 8), np.uint8); pal = 0; votes = [0, 0]
        for (y, x) in zip(*np.nonzero(cell >= 0)):
            ch = star_choice.get(int(cell[y, x]))
            if ch: votes[ch[0]] += 1
        pal = 1 if votes[1] > votes[0] else 0
        for (y, x) in zip(*np.nonzero(cell >= 0)):
            ch = star_choice.get(int(cell[y, x]))
            if ch and ch[0] == pal:
                px[y, x] = ch[1]
        tb = tile_bytes(px)
        if tb not in star_index:
            star_index[tb] = len(star_tiles); star_tiles.append(tb)
        star_map.append(star_index[tb] | (pal << 13 if star_index[tb] else 0))
emit('star_tiles', b''.join(star_tiles), comment='stars ')
emit('star_map', be16(star_map), 'u16', '64x32 cells, b13 = PAL1 ')
header.append(f'#define STAR_TILE_COUNT {len(star_tiles)}')

# ---------------------------------------------------------------- background zones
bgt = decode_bgtiles(src.region('bgtiles'))
code, color, flags = bgmap_cells(src.region('bgmap'))
zone_rows = []
