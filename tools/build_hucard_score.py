#!/usr/bin/env python3
"""Compile the verified HuCard score into relocated native music data.
Only reachable score instructions and instrument parameters are emitted; no
HuC6280 program or CPU address space is included in the cartridge.
"""
import argparse
import json
from pathlib import Path
from inspect_hucard_music import ROOT, metadata
from decode_hucard_score import decode


def compile_score(rom):
    info = metadata(rom)
    rows = decode(rom, {p for t in info['music'] for p in t['channels'] if p})
    assert all(row.get('length_code', 1) > 0 for row in rows)
    assert not any(row['op'] == 'toggle_noise' for row in rows), 'Noise music needs a native renderer'
    offsets = {0: 0}
    cursor = 1  # zero is an inactive channel, never a score instruction
    for row in rows:
        offsets[row['address']] = cursor
        cursor += len(row['bytes']) + (row['op'] == 'tempo')
    assert cursor < 65536
    score = bytearray([23])
    for row in rows:
        raw = bytearray(row['bytes'])
        if row['op'] == 'tempo':
            assert raw[1]
            raw[1:] = (0x3000 // raw[1]).to_bytes(2, 'little')
        if 'target' in row:
            raw[-2:] = offsets[row['target']].to_bytes(2, 'little')
        score.extend(raw)
    assert len(score) == cursor
    def source(addr, size):
        return rom[0x10000 + addr - 0x4000:0x10000 + addr - 0x4000 + size]
    songs = [[offsets[p] for p in t['channels']] for t in info['music']]
    assert [t['command'] for t in info['music']] == list(range(21))
    # Resolve attack/decay/release rate indices at build time.
    envelopes = []
    for ins in info['instruments']:
        env = ins['envelope_bytes'][:]
        for slot in (0, 1, 3):
            env[slot] = source(0x4259 + env[slot], 1)[0]
        envelopes.append(env)
    periods = [int.from_bytes(source(0x4279 + i * 2, 2), 'little') for i in range(128)]
    return dict(schema=1, source_sha256=info['source_sha256'], score=list(score), songs=songs,
                envelopes=envelopes, periods=periods,
                offsets={str(k): v for k, v in offsets.items()})


def emit(data, directory):
    directory.mkdir(parents=True, exist_ok=True)
    def array(name, values, ctype='unsigned char'):
        width = 16 if ctype == 'unsigned char' else 8
        lines = [', '.join(str(v) for v in values[i:i+width]) for i in range(0, len(values), width)]
        return f'static const {ctype} {name}[] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'
    text = '/* Generated by tools/build_hucard_score.py. */\n#include "hucard_score.h"\n'
    text += array('score', data['score'])
    text += array('songs', [v for row in data['songs'] for v in row], 'unsigned short')
    text += array('envelopes', [v for row in data['envelopes'] for v in row])
    text += array('periods', data['periods'], 'unsigned short')
    text += 'const HucardScoreData hucard_score_data = {score, songs, envelopes, periods};\n'
    (directory/'hucard_data.c').write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path, default=ROOT/'.local/pce-hucard/SideArms - Hyper Dyne (USA).pce')
    parser.add_argument('--output', type=Path, default=ROOT/'src/gen')
    args = parser.parse_args()
    data = compile_score(args.rom.read_bytes())
    emit(data, args.output)
    (ROOT/'.local/pce-hucard').mkdir(parents=True, exist_ok=True)
    (ROOT/'.local/pce-hucard/native-score.json').write_text(json.dumps(data) + '\n')
    print(f"HuCard: {len(data['score'])} score bytes, 21 song entries, 32 envelope records")

if __name__ == '__main__':
    main()
