def emit(name, data, ctype='u8', comment=''):
    (GEN / f'{name}.bin').write_bytes(data)
    symbols.append(name)
    header.append(f'extern const {ctype} {name}[];  /* {len(data)} bytes {comment}*/')


def be16(vals):
    return b''.join(struct.pack('>H', v & 0xffff) for v in vals)


def carr(ctype, name, vals, per=16, static=False):
    cdata.append(f'{"static " if static else ""}const {ctype} {name}[{len(vals)}] = {{')
    for i in range(0, len(vals), per):
        cdata.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    cdata.append('};')


def bank(b, a):
    return M[a] if a < 0x8000 else M[0x8000 + b * 0x4000 + a - 0x8000]


