# ------------------------------------------------------------------ attract demo
DEMO_IN = [(0x9600, 0x9800), (0x9800, 0x9A00), (0x9A00, 0x9D00), (0x9D00, 0xA000)]
MAX_DEMO_FRAMES = 4000
for k, (a, end) in enumerate(DEMO_IN):
    # B2:$8032: the pointer starts at the table, duration 1 -> the first pair is at +2;
    # a duration byte of 0 lasts 256 frames.
    out, tot, p = [], 0, a + 2
    while p < end and tot < MAX_DEMO_FRAMES:
        v, n = bank(2, p), bank(2, p + 1) or 256
        out.append((v << 8) | (n & 0xFF)); tot += n; p += 2
    carr('u16', f'fe_demo_input{k}', out, static=True)
    cdata.append(f'#define FE_DEMO_INPUT{k}_LEN {len(out)}')
cdata.append('const FeDemoInput fe_demo_inputs[4] = {')
for k in range(4):
    cdata.append(f'    {{fe_demo_input{k}, FE_DEMO_INPUT{k}_LEN}},')
cdata.append('};')
