def world_view(sx, sy):
    """MD colour indices of the Genesis 320x224 view at arcade scroll (sx, sy): camera =
    scroll + (96, 16). Returns (H, W) array of colour tuples-ids and a transparency mask."""
    wx0, wy0 = sx + 96, sy + 16
    img = np.full((224, 320), -1, np.int32)
    for py in range(0, 224 + 32, 32):
        for px in range(0, 320 + 32, 32):
            wx, wy = (wx0 + px) & 0xFFF, (wy0 + py) & 0xFFF
            cx, cy = wx >> 5, wy >> 5
            t = bgt[code[cy, cx]]
            if flags[cy, cx] & 1: t = t[:, ::-1]
            if flags[cy, cx] & 2: t = t[::-1, :]
            ids = np.where(t == 15, -1, color[cy, cx] * 16 + t.astype(np.int32))
            ox, oy = px - (wx & 31), py - (wy & 31)
            x0, y0 = max(0, ox), max(0, oy)
            x1, y1 = min(320, ox + 32), min(224, oy + 32)
            if x1 > x0 and y1 > y0:
                img[y0:y1, x0:x1] = ids[y0 - oy:y1 - oy, x0 - ox:x1 - ox]
    return img


