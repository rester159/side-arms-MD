"""Front-end / HUD data, converted from the original ROM set at build time.

Run by tools/build_assets.py after the text-layer font (font_pens, txt_lut, txt_pal,
font_blank) has been generated. Outputs (all ignored by VCS):
  res/generated/fe_*.bin      tile blobs and scene maps
  src/gen/frontend.s          .incbin wrapper
  src/gen/frontend_data.c     small tables (strings, ranking, demo inputs/scripts)
  inc/gen/frontend.h          declarations

Contents (arcade sources, see docs/frontend.md and docs/re/flow_player.md):
  * SIDE ARMS logo: the 32x8 text-layer block drawn by $0DF5 (string $0EA4, attr $70),
    pre-rendered to deduplicated Genesis tiles + a nametable.
  * Weapon bar glyphs $50-$63 in the four bar colours of $1E7C ($20 none, $25 owned,
    $23/$24 selected flash), streamed per player by hud.c.
  * Background "scenes": the fixed world views shown by the title ($0BD1: scroll $180,0)
    and the Earth intro ($13BC-$153B, 15 scroll positions), rendered from the BG ROMs and
    quantized to PAL0/PAL1 (star colours kept at the indices video.c's starfield uses).
  * Text strings (region warning, ranking, credit screen, intro, HUD messages) decoded
    from their $03BD records, default ranking ($0B34), bonus-life tables ($09EF).
  * Attract demo: recorded inputs (B2:$9600/$9800, $9A00/$9D00, read by B2:$802C) and the
    two demo scroll scripts (B1:$8000 / B1:$8074) simulated into camera-triggered events.
"""
