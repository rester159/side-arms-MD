def glyph(code, colour):
    """Arcade char (code 0-1023) in text colour 0-63 -> (32-byte Genesis tile, palette 0/1)."""
    raw = font[code * 32:code * 32 + 32]
    lut = tlut[colour * 256:colour * 256 + 256]
    return bytes(lut[b] for b in raw), tpal[colour]


def tile_px(t):
    a = np.zeros((8, 8), np.uint8)
    for y in range(8):
        for x in range(4):
            b = t[y * 4 + x]
            a[y, 2 * x] = b >> 4; a[y, 2 * x + 1] = b & 15
    return a


def px_tile(a):
    return bytes(((int(a[y, 2 * x]) & 15) << 4) | (int(a[y, 2 * x + 1]) & 15) for y in range(8) for x in range(4))


class TileSet:
    """Deduplicating tile store (with H/V flips)."""
    def __init__(self):
        self.tiles, self.index = [], {}

    def add(self, t):
        a = tile_px(t)
        for hf in (0, 1):
            for vf in (0, 1):
                b = a[:, ::-1] if hf else a
                b = b[::-1] if vf else b
                k = px_tile(b)
                if k in self.index:
                    return self.index[k], hf, vf
        self.index[t] = len(self.tiles); self.tiles.append(t)
        return len(self.tiles) - 1, 0, 0


# ------------------------------------------------------------------ $03BD text records
def text_record(a):
    """addr lo/hi, rows, cols, attr, chars ($FF n = n blanks). attr b0-5 colour, b6-7 code bits 8-9."""
    v = M[a] | M[a + 1] << 8
    rows, cols, attr = M[a + 2], M[a + 3], M[a + 4]
    codes, i = [], a + 5
    while len(codes) < rows * cols:
        if M[i] == 0xFF:
            codes += [0x27] * M[i + 1]; i += 2
        else:
            codes.append(M[i]); i += 1
    r, c = (v - 0xD000) // 64, (v - 0xD000) % 64
    return dict(row=r, col=c, rows=rows, cols=cols, attr=attr, codes=[c_ | ((attr >> 6) << 8) for c_ in codes])


